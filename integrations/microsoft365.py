"""Microsoft Graph client for tenant user lifecycle operations.

Safety rules:
- Secrets come from environment variables only and are never logged or displayed.
- dry_run mode (default) reports what WOULD happen and never claims a change was made.
- live mode raises NotConfigured when credentials are missing; it never simulates success.
- Only the operations below are implemented. Everything else is intentionally absent.
"""
import logging

import requests
from django.conf import settings
from django.core.cache import cache
from requests.adapters import HTTPAdapter
from urllib3.util.retry import Retry

log = logging.getLogger(__name__)
GRAPH = "https://graph.microsoft.com/v1.0"


class NotConfigured(Exception):
    pass


class GraphError(Exception):
    pass


class GraphClient:
    def __init__(self, cfg=None):
        self.cfg = cfg or settings.MICROSOFT365
        self.session = requests.Session()
        retry = Retry(total=3, backoff_factor=1, status_forcelist=[429, 500, 502, 503, 504],
                      allowed_methods=["GET", "POST", "PATCH"])
        self.session.mount("https://", HTTPAdapter(max_retries=retry))

    @property
    def is_configured(self):
        return all(self.cfg.get(k) for k in ("TENANT_ID", "CLIENT_ID", "CLIENT_SECRET"))

    @property
    def is_dry_run(self):
        return self.cfg.get("MODE", "dry_run") != "live"

    def _require_config(self):
        if not self.is_configured:
            raise NotConfigured("Microsoft 365 is not configured. Set M365_TENANT_ID, M365_CLIENT_ID and "
                                "M365_CLIENT_SECRET, then restart the portal.")

    def _token(self):
        cache_key = f"m365-token-{self.cfg['CLIENT_ID']}"
        token = cache.get(cache_key)
        if token:
            return token
        resp = self.session.post(
            f"https://login.microsoftonline.com/{self.cfg['TENANT_ID']}/oauth2/v2.0/token",
            data={"grant_type": "client_credentials", "client_id": self.cfg["CLIENT_ID"],
                  "client_secret": self.cfg["CLIENT_SECRET"], "scope": "https://graph.microsoft.com/.default"},
            timeout=20)
        if resp.status_code != 200:
            raise GraphError(f"Token request failed with HTTP {resp.status_code}.")
        data = resp.json()
        cache.set(cache_key, data["access_token"], max(60, int(data.get("expires_in", 3600)) - 120))
        return data["access_token"]

    def _request(self, method, path, **kwargs):
        headers = {"Authorization": f"Bearer {self._token()}"}
        resp = self.session.request(method, f"{GRAPH}{path}", headers=headers, timeout=30, **kwargs)
        if resp.status_code >= 400:
            # Do not include the response body: it may echo request data.
            raise GraphError(f"Graph {method} {path.split('?')[0]} failed with HTTP {resp.status_code}.")
        return resp.json() if resp.content else {}

    # ---- Read-only ----
    def test_connection(self):
        """Verifies credentials and that the app can read the directory."""
        if not self.is_configured:
            return {"ok": False, "message": "Not configured. Missing tenant ID, client ID or client secret."}
        try:
            self._request("GET", "/organization?$select=displayName")
            return {"ok": True, "message": "Connected. Directory read succeeded."}
        except (GraphError, requests.RequestException) as exc:
            return {"ok": False, "message": str(exc)}

    # ---- Writes (dry-run aware) ----
    def _write(self, description, func):
        if self.is_dry_run:
            log.info("M365 dry run: %s", description)
            return {"status": "dry_run", "detail": f"DRY RUN, nothing changed in Microsoft 365: {description}"}
        self._require_config()
        func()
        return {"status": "success", "detail": description}

    def create_user(self, *, upn, display_name, first_name, last_name, job_title=""):
        def action():
            self._request("POST", "/users", json={
                "accountEnabled": True, "displayName": display_name, "mailNickname": upn.split("@")[0],
                "userPrincipalName": upn, "givenName": first_name, "surname": last_name,
                "jobTitle": job_title, "usageLocation": "SA",
                # Temporary password is generated by Graph and never stored or shown by the portal.
                "passwordProfile": {"forceChangePasswordNextSignIn": True,
                                    "password": _random_password()},
            })
        return self._write(f"create Microsoft 365 user {upn}", action)

    def assign_license(self, *, upn, sku_id=None):
        sku = sku_id or self.cfg.get("DEFAULT_LICENSE_SKU_ID")
        if not sku:
            if self.is_dry_run:
                return {"status": "dry_run", "detail": "DRY RUN: no license SKU configured (M365_DEFAULT_LICENSE_SKU_ID)."}
            raise NotConfigured("M365_DEFAULT_LICENSE_SKU_ID is not set.")

        def action():
            self._request("POST", f"/users/{upn}/assignLicense",
                          json={"addLicenses": [{"skuId": sku}], "removeLicenses": []})
        return self._write(f"assign license {sku} to {upn}", action)

    def disable_user(self, *, upn):
        return self._write(f"disable account {upn}",
                           lambda: self._request("PATCH", f"/users/{upn}", json={"accountEnabled": False}))

    def revoke_sessions(self, *, upn):
        return self._write(f"revoke sign-in sessions for {upn}",
                           lambda: self._request("POST", f"/users/{upn}/revokeSignInSessions", json={}))


def _random_password():
    import secrets
    return secrets.token_urlsafe(24) + "Aa1!"


def run_action(action, *, upn, display_name="", first_name="", last_name="", job_title=""):
    client = GraphClient()
    if action == "m365_create_user":
        return client.create_user(upn=upn, display_name=display_name, first_name=first_name,
                                  last_name=last_name, job_title=job_title)
    if action == "m365_assign_license":
        return client.assign_license(upn=upn)
    if action == "m365_disable_user":
        return client.disable_user(upn=upn)
    if action == "m365_revoke_sessions":
        return client.revoke_sessions(upn=upn)
    raise ValueError(f"Unknown Microsoft 365 action: {action}")
